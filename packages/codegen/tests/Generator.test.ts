import { afterEach, beforeEach, describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import Generator, { loadConfig } from '../src/Generator.js';
import { createTempDir, startSpecServer, writeSpec } from './helpers.js';

describe('Generator', () => {
  let dir: string;
  let cleanup: () => Promise<void>;

  beforeEach(async () => {
    ({ dir, cleanup } = await createTempDir());
  });

  afterEach(() => cleanup());

  it('should write typescript paths if the source is a local file', async () => {
    const from = await writeSpec(dir);
    const to = join(dir, 'schema.d.ts');

    await new Generator({ from, to }).generate();

    const output = await readFile(to, 'utf8');

    assert.match(output, /export interface paths/);
    assert.match(output, /"\/ping"/);
  });

  it('should start the output with the auto-generated banner if the schema is converted', async () => {
    const from = await writeSpec(dir);
    const to = join(dir, 'schema.d.ts');

    await new Generator({ from, to }).generate();

    assert.match(await readFile(to, 'utf8'), /^\/\*\*\n \* This file was auto-generated by openapi-typescript\./);
  });

  it('should create missing directories if the output path is nested', async () => {
    const from = await writeSpec(dir);
    const to = join(dir, 'a', 'b', 'schema.d.ts');

    await new Generator({ from, to }).generate();

    assert.match(await readFile(to, 'utf8'), /export interface paths/);
  });

  it('should load the spec over http if the source is a url', async () => {
    const server = await startSpecServer();
    const to = join(dir, 'schema.d.ts');

    try {
      await new Generator({ from: server.url, to }).generate();
    } finally {
      await server.close();
    }

    assert.match(await readFile(to, 'utf8'), /"\/ping"/);
  });

  it('should reject and not write the output if the source file does not exist', async () => {
    const to = join(dir, 'schema.d.ts');

    await assert.rejects(new Generator({ from: join(dir, 'missing.json'), to }).generate());
    await assert.rejects(readFile(to), { code: 'ENOENT' });
  });

  it('should reject if the server responds with an error status', async () => {
    const server = await startSpecServer(500);

    try {
      await assert.rejects(new Generator({ from: server.url, to: join(dir, 'schema.d.ts') }).generate());
    } finally {
      await server.close();
    }
  });

  it('should return the file content without writing it if render() is called', async () => {
    const from = await writeSpec(dir);
    const to = join(dir, 'schema.d.ts');

    const content = await new Generator({ from, to }).render();

    assert.match(content, /export interface paths/);
    await assert.rejects(readFile(to, 'utf8'), /ENOENT/);
  });

  it('should return true if check() finds the output up to date', async () => {
    const from = await writeSpec(dir);
    const generator = new Generator({ from, to: join(dir, 'schema.d.ts') });

    await generator.generate();

    assert.equal(await generator.check(), true);
  });

  it('should return false and not write if check() finds no output file', async () => {
    const from = await writeSpec(dir);
    const to = join(dir, 'schema.d.ts');

    assert.equal(await new Generator({ from, to }).check(), false);
    await assert.rejects(readFile(to, 'utf8'), /ENOENT/);
  });

  it('should return false and keep the file if check() finds the output out of date', async () => {
    const from = await writeSpec(dir);
    const to = join(dir, 'schema.d.ts');

    await writeFile(to, 'old');

    assert.equal(await new Generator({ from, to }).check(), false);
    assert.equal(await readFile(to, 'utf8'), 'old');
  });

  it('should export loadConfig for programmatic use', () => {
    assert.equal(typeof loadConfig, 'function');
  });
});
